"""
Build the league parity fixture: a synthetic 10-team Sleeper league made
from the current site data, plus what the Python engines return for it.

frontend/e2e/league-parity.spec.ts runs the TypeScript port on the same
league and requires identical waivers, roster and add/drop moves.

    python backend/scripts/make_league_fixture.py
"""

import json
import math
import sys
from pathlib import Path

import pandas as pd

BACKEND = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND))

from config import STATIC_DATA_DIR  # noqa: E402
from move_engine import generate_add_drop_recommendations  # noqa: E402
from team_engine import build_team_roster  # noqa: E402
from waiver_engine import create_player_key, find_available_players  # noqa: E402

OUT = BACKEND.parent / "frontend" / "e2e" / "fixtures" / "league.json"
ROSTER_POSITIONS = ["QB", "RB", "RB", "WR", "WR", "TE", "FLEX", "K", "DEF"] + ["BN"] * 6 + ["IR"]


def load(name):
    return json.loads((STATIC_DATA_DIR / name).read_text())


def num(value):
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return None
    return float(value)


def main():
    meta = load("meta.json")
    projections = load("projections.json")["players"]
    breakouts = load("breakouts.json")["players"]
    league_players = load("league_players.json")["players"]

    by_gsis = {v[3]: sid for sid, v in league_players.items() if v[3]}
    by_key = {create_player_key(v[0], v[1]): sid for sid, v in league_players.items()}

    def sleeper_id(p):
        return by_gsis.get(p["player_id"]) or by_key.get(create_player_key(p["name"], p["position"]))

    ranked = {
        pos: [p for p in projections if p["position"] == pos and not p["on_bye"] and sleeper_id(p)]
        for pos in ("RB", "WR", "TE")
    }
    byes = [p for p in projections if p["on_bye"] and sleeper_id(p)]
    others = {pos: [sid for sid, v in league_players.items() if v[1] == pos] for pos in ("QB", "K", "DEF")}

    pick = lambda pos, rank: sleeper_id(ranked[pos][rank])  # noqa: E731
    mine = {
        "QB": others["QB"][0], "RB1": pick("RB", 8), "RB2": pick("RB", 30),
        "WR1": pick("WR", 10), "WR2": pick("WR", 40), "TE": pick("TE", 9),
        "FLEX": pick("WR", 55), "K": others["K"][0], "DEF": others["DEF"][0],
    }
    bench = [pick("RB", 45), pick("RB", 60), pick("WR", 70), pick("TE", 20), sleeper_id(byes[0])]
    reserve = [pick("RB", 80)]
    my_ids = set(mine.values()) | set(bench) | set(reserve)

    # The other nine teams own the top of every position.
    taken = [
        sleeper_id(p)
        for pos, limit in (("RB", 27), ("WR", 36), ("TE", 12))
        for p in ranked[pos][:limit]
        if sleeper_id(p) not in my_ids
    ]
    rosters = [{
        "roster_id": 1, "owner_id": "me", "co_owners": None,
        "starters": list(mine.values()), "players": list(mine.values()) + bench + reserve,
        "reserve": reserve, "taxi": None,
    }]
    for i in range(9):
        rosters.append({
            "roster_id": i + 2, "owner_id": f"u{i + 2}", "co_owners": None,
            "starters": [], "players": taken[i::9], "reserve": None, "taxi": None,
        })
    league = {
        "league_id": "fixture", "name": "Parity League", "season": str(meta["season"]),
        "status": "in_season", "total_rosters": 10, "roster_positions": ROSTER_POSITIONS,
    }
    users = [{"user_id": "me", "display_name": "me"}] + [
        {"user_id": f"u{i + 2}", "display_name": f"Team {i + 2}"} for i in range(9)
    ]

    # Python engines, fed the same rows the site publishes.
    pool = pd.DataFrame([
        {
            "player_id": p["player_id"], "player_display_name": p["name"], "position": p["position"],
            "team": p["team"], "week": p["data_week"], "projected_points": p["projected_points"],
            "fantasy_points_ppr_avg_3": p["recent_avg"], "on_bye": bool(p["on_bye"]),
        }
        for p in projections
    ])
    breakouts_df = pd.DataFrame([
        {"player_id": b["player_id"], "player_display_name": b["name"], "position": b["position"],
         "breakout_score": b["breakout_score"]}
        for b in breakouts
    ])
    sleeper = {sid: {"full_name": v[0], "position": v[1], "team": v[2], "gsis_id": v[3]} for sid, v in league_players.items()}
    owned = {sid for r in rosters for sid in (r["players"] or []) + (r["reserve"] or [])}

    waivers = find_available_players(pool, breakouts_df, sleeper, owned, meta["data_through_week"])
    team = build_team_roster(rosters[0], league, sleeper, pool)
    moves = generate_add_drop_recommendations(team, waivers, max_recommendations=5)

    used = owned
    fixture = {
        "note": "Generated by backend/scripts/make_league_fixture.py. Do not edit by hand.",
        "data_generated_at": meta["generated_at"],
        "completed_week": meta["data_through_week"],
        "league": league,
        "rosters": rosters,
        "users": users,
        "user_id": "me",
        "league_players": {sid: league_players[sid] for sid in sorted(used)},
        "expected": {
            "waivers": [[r["player_display_name"], float(r["waiver_score"])] for _, r in waivers.iterrows()],
            "team": [
                [str(r["player_id"]), r["slot"], r["roster_status"], num(r["projected_points"]), r["match_method"]]
                for _, r in team.iterrows()
            ],
            "moves": [
                {
                    "add": m["add_player"], "drop": m["drop_player"],
                    "starter_gain": float(m["starter_gain"]), "asset_gain": float(m["asset_gain"]),
                    "depth_penalty": float(m["depth_penalty"]), "move_score": float(m["move_score"]),
                    "current": float(m["current_lineup_projection"]), "new": float(m["new_lineup_projection"]),
                    "move_type": m["move_type"], "confidence": m["confidence"],
                }
                for _, m in moves.iterrows()
            ],
        },
    }
    OUT.write_text(json.dumps(fixture, indent=1) + "\n")
    print(f"Wrote {OUT}: {len(fixture['expected']['waivers'])} waivers, "
          f"{len(fixture['expected']['team'])} roster rows, {len(fixture['expected']['moves'])} moves")


if __name__ == "__main__":
    main()
